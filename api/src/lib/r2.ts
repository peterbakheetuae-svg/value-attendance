/**
 * Cloudflare R2 (S3-compatible) client — no SDK: AWS Signature V4 with node:crypto only (no new dependency).
 *
 * Credentials live ONLY in the API host's environment (never in Flutter, Git, logs or build output):
 *   R2_ACCOUNT_ID, R2_ACCESS_KEY_ID, R2_SECRET_ACCESS_KEY, R2_BUCKET, R2_JURISDICTION ('eu' | '' — default 'eu')
 * The bucket is private: this module never builds a public URL. Presigned URLs are short-lived (≤ 300 s),
 * single-object, and must never be logged, stored or put in notifications.
 */
import { createHash, createHmac } from 'node:crypto';

export interface R2Config {
  accountId: string;
  accessKeyId: string;
  secretAccessKey: string;
  bucket: string;
  /** 'eu' → <account>.eu.r2.cloudflarestorage.com ; '' → <account>.r2.cloudflarestorage.com */
  jurisdiction: string;
  /** override for tests / other S3 endpoints: full origin, e.g. http://127.0.0.1:9000 */
  endpoint?: string;
  region?: string;
}

/** Reads the R2 config from the environment; null when R2 is not configured (the API then keeps files in Postgres). */
export function r2ConfigFromEnv(env: NodeJS.ProcessEnv = process.env): R2Config | null {
  const accountId = env.R2_ACCOUNT_ID?.trim();
  const accessKeyId = env.R2_ACCESS_KEY_ID?.trim();
  const secretAccessKey = env.R2_SECRET_ACCESS_KEY?.trim();
  const bucket = env.R2_BUCKET?.trim();
  if (!accountId || !accessKeyId || !secretAccessKey || !bucket) return null;
  if (!/^[a-f0-9]{32}$/.test(accountId)) throw new Error('R2_ACCOUNT_ID is not a Cloudflare account id');
  if (!/^[a-z0-9][a-z0-9-]{1,61}[a-z0-9]$/.test(bucket)) throw new Error('R2_BUCKET is not a valid bucket name');
  const jurisdiction = (env.R2_JURISDICTION ?? 'eu').trim().toLowerCase();
  if (!['eu', ''].includes(jurisdiction)) throw new Error('R2_JURISDICTION must be "eu" or empty');
  return { accountId, accessKeyId, secretAccessKey, bucket, jurisdiction };
}

const sha256hex = (d: string | Uint8Array) => createHash('sha256').update(d).digest('hex');
const hmac = (k: string | Buffer, d: string) => createHmac('sha256', k).update(d).digest();

/** RFC 3986 encoding as S3 SigV4 wants it ('/' kept in paths). */
export function uriEncode(s: string, keepSlash = false): string {
  let out = '';
  for (const ch of Buffer.from(s, 'utf8')) {
    const c = String.fromCharCode(ch);
    if (/[A-Za-z0-9\-._~]/.test(c) || (keepSlash && c === '/')) out += c;
    else out += '%' + ch.toString(16).toUpperCase().padStart(2, '0');
  }
  return out;
}

/** Object keys are generated by the server only: '<area>/<yyyy>/<mm>/<uuid>' — no user text ever reaches a key. */
export function assertSafeKey(key: string): void {
  if (!/^[a-z0-9][a-z0-9_\-/]{2,200}$/.test(key) || key.includes('//') || key.includes('..') || key.endsWith('/')) {
    throw new Error('unsafe object key');
  }
}

export function signingKey(secret: string, date: string, region: string, service = 's3'): Buffer {
  return hmac(hmac(hmac(hmac('AWS4' + secret, date), region), service), 'aws4_request');
}

interface SignInput {
  method: string;
  host: string;
  path: string;                      // already URI-encoded, starting with '/'
  query?: Record<string, string>;
  headers?: Record<string, string>;  // lower-case names
  payloadHash: string;               // hex sha256 or 'UNSIGNED-PAYLOAD'
  amzDate: string;                   // YYYYMMDDTHHMMSSZ
  region: string;
  accessKeyId: string;
  secretAccessKey: string;
}

function canonicalQuery(q: Record<string, string>): string {
  return Object.keys(q).sort().map((k) => `${uriEncode(k)}=${uriEncode(q[k])}`).join('&');
}

/** Builds the SigV4 signature for a request (header auth). Exported for test vectors. */
export function signV4(i: SignInput) {
  const date = i.amzDate.slice(0, 8);
  const scope = `${date}/${i.region}/s3/aws4_request`;
  const headers: Record<string, string> = { ...(i.headers ?? {}), host: i.host };
  const names = Object.keys(headers).map((h) => h.toLowerCase()).sort();
  const canonHeaders = names.map((n) => `${n}:${String(headers[n]).trim().replace(/\s+/g, ' ')}\n`).join('');
  const signedHeaders = names.join(';');
  const creq = [i.method, i.path, canonicalQuery(i.query ?? {}), canonHeaders, signedHeaders, i.payloadHash].join('\n');
  const sts = ['AWS4-HMAC-SHA256', i.amzDate, scope, sha256hex(creq)].join('\n');
  const signature = createHmac('sha256', signingKey(i.secretAccessKey, date, i.region)).update(sts).digest('hex');
  return { signature, signedHeaders, scope, canonicalRequest: creq, stringToSign: sts };
}

/** Presigned URL (query auth). Exported for test vectors. */
export function presignV4(p: {
  method: 'GET' | 'PUT'; host: string; path: string; region: string; accessKeyId: string; secretAccessKey: string;
  amzDate: string; expiresSec: number; extraQuery?: Record<string, string>; signedHeaders?: Record<string, string>; scheme?: string;
}): string {
  const date = p.amzDate.slice(0, 8);
  const hdrs = { ...(p.signedHeaders ?? {}) };
  const names = ['host', ...Object.keys(hdrs).map((h) => h.toLowerCase())].sort();
  const query: Record<string, string> = {
    ...(p.extraQuery ?? {}),
    'X-Amz-Algorithm': 'AWS4-HMAC-SHA256',
    'X-Amz-Credential': `${p.accessKeyId}/${date}/${p.region}/s3/aws4_request`,
    'X-Amz-Date': p.amzDate,
    'X-Amz-Expires': String(p.expiresSec),
    'X-Amz-SignedHeaders': names.join(';'),
  };
  const { signature } = signV4({
    method: p.method, host: p.host, path: p.path, query, headers: hdrs, payloadHash: 'UNSIGNED-PAYLOAD',
    amzDate: p.amzDate, region: p.region, accessKeyId: p.accessKeyId, secretAccessKey: p.secretAccessKey,
  });
  return `${p.scheme ?? 'https'}://${p.host}${p.path}?${canonicalQuery(query)}&X-Amz-Signature=${signature}`;
}

const amzNow = () => new Date().toISOString().replace(/[-:]/g, '').replace(/\.\d{3}/, '');

export class R2Error extends Error {
  constructor(message: string, readonly status: number, readonly code?: string) { super(message); }
}

export interface PutResult { etag: string | null; }
export interface HeadResult { size: number; contentType: string | null; sha256: string | null; etag: string | null; }

/** Minimal R2 object client. Every call is path-style on the private bucket; no list / no bucket admin. */
export class R2Client {
  private readonly host: string;
  private readonly scheme: string;
  private readonly region: string;
  constructor(private readonly c: R2Config, private readonly fetchImpl: typeof fetch = fetch) {
    if (c.endpoint) {
      const u = new URL(c.endpoint);
      this.host = u.host; this.scheme = u.protocol.replace(':', '');
    } else {
      this.host = c.jurisdiction ? `${c.accountId}.${c.jurisdiction}.r2.cloudflarestorage.com` : `${c.accountId}.r2.cloudflarestorage.com`;
      this.scheme = 'https';
    }
    this.region = c.region ?? 'auto';
  }

  private path(key: string) { assertSafeKey(key); return `/${uriEncode(this.c.bucket)}/${uriEncode(key, true)}`; }

  private async send(method: string, key: string, body?: Uint8Array, extra: Record<string, string> = {}, timeoutMs = 20000) {
    const amzDate = amzNow();
    const payloadHash = body ? sha256hex(body) : sha256hex('');
    const headers: Record<string, string> = { ...extra, 'x-amz-content-sha256': payloadHash, 'x-amz-date': amzDate };
    const path = this.path(key);
    const { signature, signedHeaders, scope } = signV4({
      method, host: this.host, path, headers, payloadHash, amzDate, region: this.region,
      accessKeyId: this.c.accessKeyId, secretAccessKey: this.c.secretAccessKey,
    });
    headers.authorization = `AWS4-HMAC-SHA256 Credential=${this.c.accessKeyId}/${scope}, SignedHeaders=${signedHeaders}, Signature=${signature}`;
    const ctl = new AbortController();
    const t = setTimeout(() => ctl.abort(), timeoutMs);
    try {
      return await this.fetchImpl(`${this.scheme}://${this.host}${path}`, { method, headers, body: body as unknown as BodyInit | undefined, signal: ctl.signal });
    } catch (e) {
      throw new R2Error(`storage unreachable (${method})`, 503, (e as Error).name);
    } finally { clearTimeout(t); }
  }

  private static async fail(res: Response, op: string): Promise<never> {
    const text = await res.text().catch(() => '');
    const code = /<Code>([^<]+)<\/Code>/.exec(text)?.[1];
    // never include the URL (it may carry a signature) or the response body in the message
    throw new R2Error(`storage ${op} failed`, res.status, code);
  }

  /** Writes an object only if the key is free (no overwrite): If-None-Match: * */
  async put(key: string, data: Uint8Array, contentType: string, sha256: string): Promise<PutResult> {
    if (!/^[a-f0-9]{64}$/.test(sha256) || sha256hex(data) !== sha256) throw new R2Error('sha256 mismatch before upload', 400);
    const res = await this.send('PUT', key, data, {
      'content-type': contentType, 'content-length': String(data.byteLength), 'if-none-match': '*', 'x-amz-meta-sha256': sha256,
    });
    if (!res.ok) await R2Client.fail(res, 'put');
    return { etag: res.headers.get('etag') };
  }

  async head(key: string): Promise<HeadResult | null> {
    const res = await this.send('HEAD', key);
    if (res.status === 404) return null;
    if (!res.ok) await R2Client.fail(res, 'head');
    return {
      size: Number(res.headers.get('content-length') ?? -1), contentType: res.headers.get('content-type'),
      sha256: res.headers.get('x-amz-meta-sha256'), etag: res.headers.get('etag'),
    };
  }

  /** Reads the whole object (files here are ≤ a few MB) and verifies it against the expected SHA-256. */
  async get(key: string, expectSha256?: string): Promise<{ data: Uint8Array; contentType: string | null } | null> {
    const res = await this.send('GET', key, undefined, {}, 30000);
    if (res.status === 404) return null;
    if (!res.ok) await R2Client.fail(res, 'get');
    const data = new Uint8Array(await res.arrayBuffer());
    if (expectSha256 && sha256hex(data) !== expectSha256) throw new R2Error('stored object failed its integrity check', 502, 'IntegrityMismatch');
    return { data, contentType: res.headers.get('content-type') };
  }

  async delete(key: string): Promise<void> {
    const res = await this.send('DELETE', key);
    if (!res.ok && res.status !== 404) await R2Client.fail(res, 'delete');
  }

  /** Short-lived presigned GET for a single object (download), ≤ 300 s, with a forced download name. */
  presignGet(key: string, filename: string, expiresSec = 60): string {
    if (expiresSec < 1 || expiresSec > 300) throw new Error('presign expiry out of range');
    const safe = filename.replace(/[\r\n"\\]/g, '_').slice(0, 150) || 'file';
    return presignV4({
      method: 'GET', host: this.host, path: this.path(key), region: this.region, scheme: this.scheme,
      accessKeyId: this.c.accessKeyId, secretAccessKey: this.c.secretAccessKey, amzDate: amzNow(), expiresSec,
      extraQuery: { 'response-content-disposition': `attachment; filename*=UTF-8''${uriEncode(safe)}` },
    });
  }
}

export const sha256Hex = sha256hex;
